<?php

namespace App\Services;

use App\Models\InventoryTransaction;
use App\Models\Product;
use App\Models\PurchaseOrder;
use App\Models\PurchaseOrderItem;
use Illuminate\Support\Collection;
use Illuminate\Support\Facades\DB;

/**
 * Business logic for automated replenishment.
 *
 *   Reorder point = (average daily usage x lead time) + safety stock
 */
class ReorderService
{
    /** @var array|null product_id => units sold in the usage window (loaded once per run) */
    protected $usageTotals;

    public function calculateAverageDailyUsage(Product $product): float
    {
        $days = max(1, (int) config('procurement.usage_window_days'));

        if ($this->usageTotals !== null) {
            $total = $this->usageTotals[$product->id] ?? 0;
        } else {
            $total = InventoryTransaction::where('product_id', $product->id)
                ->where('type', 'out')
                ->where('created_at', '>=', now()->subDays($days))
                ->sum('quantity');
        }

        return round($total / $days, 2);
    }

    public function calculateReorderPoint(Product $product): int
    {
        $averageDailyUsage = $this->calculateAverageDailyUsage($product);
        $leadTime = optional($product->supplier)->lead_time_days ?? config('procurement.default_lead_time_days');
        $safetyStock = $product->reorder_level ?? config('procurement.default_safety_stock');

        return (int) ceil(($averageDailyUsage * $leadTime) + $safetyStock);
    }

    /**
     * Simplified EOQ: order back up to (reorder point + review-period demand), then respect the
     * supplier's minimum order quantity and round up to a whole number of packs.
     */
    public function calculateOptimalOrderQuantity(Product $product): int
    {
        $reorderPoint = $this->calculateReorderPoint($product);
        $reviewDemand = (int) ceil($this->calculateAverageDailyUsage($product) * config('procurement.review_period_days'));
        $safetyStock = $product->reorder_level ?? config('procurement.default_safety_stock');

        $targetLevel = max($reorderPoint + $reviewDemand, $safetyStock * 2);
        $quantity = max($targetLevel - $product->quantity, 1);
        $quantity = max($quantity, max(1, (int) $product->min_order_quantity));

        $pack = max(1, (int) $product->pack_size);

        return (int) (ceil($quantity / $pack) * $pack);
    }

    /**
     * Products at or below their reorder point that have an active supplier
     * and are not already on an open purchase order.
     */
    public function getProductsNeedingReorder(): Collection
    {
        $this->loadUsageTotals();

        $alreadyOrdered = PurchaseOrderItem::whereHas('purchaseOrder', function ($q) {
            $q->active();
        })->pluck('product_id')->filter()->unique()->all();

        return Product::with('supplier')
            ->whereNotNull('supplier_id')
            ->whereHas('supplier', function ($q) {
                $q->where('is_active', true)->whereNull('deleted_at');
            })
            ->orderBy('name')
            ->get()
            ->reject(function ($product) use ($alreadyOrdered) {
                return in_array($product->id, $alreadyOrdered, true);
            })
            ->filter(function ($product) {
                return $product->quantity <= $this->calculateReorderPoint($product);
            })
            ->values();
    }

    public function groupProductsBySupplier($products): Collection
    {
        return collect($products)->groupBy('supplier_id');
    }

    /**
     * Create one draft purchase order per supplier for everything that needs reordering.
     *
     * @return Collection<int, PurchaseOrder>
     */
    public function generatePurchaseOrders(): Collection
    {
        $products = $this->getProductsNeedingReorder();
        $groupedBySupplier = $this->groupProductsBySupplier($products);
        $created = collect();

        foreach ($groupedBySupplier as $supplierId => $supplierProducts) {
            $supplier = $supplierProducts->first()->supplier;

            DB::transaction(function () use ($supplier, $supplierProducts, $created) {
                $order = PurchaseOrder::create([
                    'reference_number' => PurchaseOrder::generateReferenceNumber(),
                    'supplier_id' => $supplier->id,
                    'status' => PurchaseOrder::DRAFT,
                    'order_date' => today(),
                    'expected_delivery_date' => today()->addDays($supplier->lead_time_days),
                    'notes' => 'Auto-generated by the daily reorder check on ' . now()->format('M d, Y H:i') . '.',
                    'terms' => 'Payment terms: ' . $supplier->payment_terms,
                    'auto_generated' => true,
                    'created_by' => null,
                ]);

                foreach ($supplierProducts as $product) {
                    $order->items()->create([
                        'product_id' => $product->id,
                        'product_name' => $product->name,
                        'sku' => $product->sku,
                        'quantity' => $this->calculateOptimalOrderQuantity($product),
                        'unit_price' => $product->cost_price,
                    ]);
                }

                $order->calculateTotal();

                if ($supplier->minimum_order_amount > 0 && $order->subtotal < $supplier->minimum_order_amount) {
                    $order->update(['notes' => $order->notes . "\nWarning: subtotal is below this supplier's minimum order amount of "
                        . config('procurement.currency') . number_format($supplier->minimum_order_amount, 2) . '.']);
                }

                $created->push($order->load(['supplier', 'items']));
            });
        }

        return $created;
    }

    /** Rows for the dashboard widget / API. */
    public function reorderAlerts(): array
    {
        return $this->getProductsNeedingReorder()->map(function ($product) {
            return [
                'product_id' => $product->id,
                'name' => $product->name,
                'sku' => $product->sku,
                'quantity' => $product->quantity,
                'reorder_point' => $this->calculateReorderPoint($product),
                'suggested_quantity' => $this->calculateOptimalOrderQuantity($product),
                'supplier' => optional($product->supplier)->company_name,
            ];
        })->values()->all();
    }

    protected function loadUsageTotals(): void
    {
        $this->usageTotals = InventoryTransaction::where('type', 'out')
            ->where('created_at', '>=', now()->subDays(max(1, (int) config('procurement.usage_window_days'))))
            ->groupBy('product_id')
            ->selectRaw('product_id, SUM(quantity) as total')
            ->pluck('total', 'product_id')
            ->all();
    }
}
